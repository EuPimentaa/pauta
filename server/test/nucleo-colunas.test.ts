/** Colunas (API.md §4.6). */
import { describe, test } from 'node:test'
import assert from 'node:assert/strict'
import { rodar, um } from '../src/db.ts'
import { ambiente, eventos, ultimoSeq } from './ajuda.ts'

describe('colunas', () => {
  test('criar (qualquer usuário), no fim ou na posição; quadro arquivado → 422; pessoa repetida → 409', async () => {
    const a = await ambiente()
    const eu = a.como(a.pessoas.design)
    const q = a.quadros.criacao.quadro.id
    const r = await eu.post(`/api/quadros/${q}/colunas`, { nome: 'Ideias', cor: 'amarelo', limiteWip: 3 })
    assert.equal(r.status, 201)
    assert.equal(r.corpo.pos, a.coluna('criacao', 'Concluído').pos + 1024)
    const p = await eu.post(`/api/quadros/${q}/colunas`, { nome: 'Antes', posicao: { depoisDeId: null } })
    assert.ok(p.corpo.pos < a.coluna('criacao', 'Fila').pos)
    const pessoa = await eu.post(`/api/quadros/${q}/colunas`, { nome: 'Rafa 2', responsavelId: a.pessoas.design.id })
    assert.equal(pessoa.status, 409)
    assert.equal((await eu.post(`/api/quadros/${q}/colunas`, { nome: 'X', responsavelId: a.pessoas.web.id, papel: 'aguardando_cliente' })).status, 400)
    assert.equal((await eu.post(`/api/quadros/${q}/colunas`, { nome: '' })).status, 400)
    assert.equal((await eu.post(`/api/quadros/${q}/colunas`, { nome: 'Z', limiteWip: 0 })).status, 400)
    await a.como(a.pessoas.admin).post(`/api/quadros/${a.quadros.social.quadro.id}/arquivar`)
    assert.equal((await eu.post(`/api/quadros/${a.quadros.social.quadro.id}/colunas`, { nome: 'Nova' })).status, 422)
  })

  test('PATCH: renomear, cor, WIP, arrastar; pessoa com papel ≠ normal → 400; pessoa repetida → 409', async () => {
    const a = await ambiente()
    const eu = a.como(a.pessoas.am)
    const pronto = a.coluna('criacao', 'Pronto')
    const r = await eu.patch(`/api/colunas/${pronto.id}`, { nome: 'Pronto para enviar', cor: null, limiteWip: 5, posicao: { depoisDeId: null } })
    assert.equal(r.status, 200)
    assert.equal(r.corpo.coluna.nome, 'Pronto para enviar')
    assert.equal(r.corpo.coluna.cor, null)
    assert.ok(r.corpo.coluna.pos < a.coluna('criacao', 'Fila').pos)
    assert.deepEqual(r.corpo.concluidas, [])
    const design = a.coluna('criacao', 'Design')
    const t = await eu.patch(`/api/colunas/${design.id}`, { papel: 'aguardando_cliente' })
    assert.equal(t.status, 400)
    assert.equal(t.corpo.erro.mensagem, 'Tire a pessoa da coluna antes.')
    assert.equal((await eu.patch(`/api/colunas/${pronto.id}`, { responsavelId: a.pessoas.design2.id })).status, 409)
    const ok = await eu.patch(`/api/colunas/${pronto.id}`, { responsavelId: a.pessoas.web.id })
    assert.equal(ok.corpo.coluna.responsavelId, a.pessoas.web.id)
    assert.equal((await eu.patch('/api/colunas/nada', { nome: 'X' })).status, 404)
  })

  test('virar concluida conclui as abertas sem repetição; deixar de ser não desmarca', async () => {
    const a = await ambiente()
    const pronto = a.coluna('criacao', 'Pronto')
    const d1 = await a.criarDemanda({ colunaId: pronto.id, prazo: '2026-10-20', repetir: 'semanal' })
    const d2 = await a.criarDemanda({ colunaId: pronto.id })
    const seq = ultimoSeq(a.db)
    const r = await a.como(a.pessoas.am).patch(`/api/colunas/${pronto.id}`, { papel: 'concluida' })
    assert.equal(r.status, 200)
    assert.deepEqual([...r.corpo.concluidas].sort(), [d1.id, d2.id].sort())
    assert.equal(um<{ n: number }>(a.db, "SELECT count(*) AS n FROM demanda WHERE origem = 'repeticao'")!.n, 0)
    const ev = eventos(a.db, seq).filter((e) => e.entidade === 'demanda')
    assert.ok(ev.every((e) => e.campos!.includes('concluidaEm')))
    const atv = um<{ dados: string }>(a.db, "SELECT dados FROM atividade WHERE tipo = 'demanda.concluida' AND demanda_id = ?", d1.id)!
    assert.equal(JSON.parse(atv.dados).via, 'papel')
    await a.como(a.pessoas.am).patch(`/api/colunas/${pronto.id}`, { papel: 'normal' })
    assert.ok(um(a.db, 'SELECT concluida_em FROM demanda WHERE id = ? AND concluida_em IS NOT NULL', d1.id))
  })

  test('arquivar: com card → 409; só com concluídas antigas → 200 e elas são arquivadas; desliga automações', async () => {
    const a = await ambiente()
    const eu = a.como(a.pessoas.am)
    const fila = a.coluna('criacao', 'Fila')
    await a.criarDemanda()
    const r = await eu.post(`/api/colunas/${fila.id}/arquivar`)
    assert.equal(r.status, 409)
    assert.equal(r.corpo.erro.mensagem, 'Mova ou arquive os cards antes.')

    const nova = (await eu.post(`/api/quadros/${a.quadros.criacao.quadro.id}/colunas`, { nome: 'Velhas' })).corpo
    const d = await a.criarDemanda({ colunaId: nova.id })
    rodar(a.db, "UPDATE demanda SET concluida_em = '2026-10-01T10:00:00.000Z' WHERE id = ?", d.id)
    rodar(a.db, `INSERT INTO automacao_quadro (quadro_id, gatilho, destino_quadro_id, destino_coluna_id, atualizado_em)
                 VALUES (?, 'concluida', ?, ?, '2026-10-14T13:00:00.000Z')`, a.quadros.social.quadro.id, a.quadros.criacao.quadro.id, nova.id)
    const ok = await eu.post(`/api/colunas/${nova.id}/arquivar`)
    assert.equal(ok.status, 200)
    assert.deepEqual(ok.corpo.concluidasArquivadas, [d.id])
    assert.deepEqual(ok.corpo.automacoesDesligadas, [{ quadroId: a.quadros.social.quadro.id, gatilho: 'concluida' }])
    assert.ok(ok.corpo.coluna.arquivadaEm)
    assert.equal((await eu.post(`/api/colunas/${nova.id}/arquivar`)).status, 409)
    // restaurar no fim; coluna de pessoa que já tem outra → sem a pessoa
    const v = await eu.post(`/api/colunas/${nova.id}/restaurar`)
    assert.equal(v.status, 200)
    assert.equal(v.corpo.arquivadaEm, null)
    assert.equal((await eu.post(`/api/colunas/${nova.id}/restaurar`)).status, 409)
  })

  test('arquivar coluna destino de automação: a equipe recebe 403 (arquivar não desliga a automação por ela)', async () => {
    const a = await ambiente()
    const agendar = a.coluna('social', 'Agendar') // destino da automação "aprovado" da Criação
    const r = await a.como(a.pessoas.design).post(`/api/colunas/${agendar.id}/arquivar`)
    assert.equal(r.status, 403)
    assert.equal(r.corpo.erro.codigo, 'sem_permissao')
    assert.equal(r.corpo.erro.mensagem, 'Uma automação leva cards para esta coluna. Peça ao atendimento ou ao admin para arquivá-la.')
    assert.equal(um<{ ativa: number }>(a.db, "SELECT ativa FROM automacao_quadro WHERE gatilho = 'aprovado'")!.ativa, 1)
    assert.equal(um<{ arquivada_em: string | null }>(a.db, 'SELECT arquivada_em FROM coluna WHERE id = ?', agendar.id)!.arquivada_em, null)
    // sem automação ativa para ela, a equipe arquiva como sempre; o atendimento arquiva a de automação e a desliga
    assert.equal((await a.como(a.pessoas.design).post(`/api/colunas/${a.coluna('social', 'Publicado').id}/arquivar`)).status, 200)
    const ok = await a.como(a.pessoas.am).post(`/api/colunas/${agendar.id}/arquivar`)
    assert.equal(ok.status, 200)
    assert.deepEqual(ok.corpo.automacoesDesligadas, [{ quadroId: a.quadros.criacao.quadro.id, gatilho: 'aprovado' }])
  })

  test('restaurar coluna de pessoa que já tem outra ativa: volta sem a pessoa; em quadro arquivado → 422', async () => {
    const a = await ambiente()
    const eu = a.como(a.pessoas.am)
    const design = a.coluna('criacao', 'Design')
    assert.equal((await eu.post(`/api/colunas/${design.id}/arquivar`)).status, 200)
    await eu.post(`/api/quadros/${a.quadros.criacao.quadro.id}/colunas`, { nome: 'Rafa', responsavelId: a.pessoas.design.id })
    const v = await eu.post(`/api/colunas/${design.id}/restaurar`)
    assert.equal(v.corpo.responsavelId, null)
    const agendar = a.coluna('social', 'Agendar')
    await eu.post(`/api/colunas/${agendar.id}/arquivar`)
    await a.como(a.pessoas.admin).post(`/api/quadros/${a.quadros.social.quadro.id}/arquivar`)
    assert.equal((await eu.post(`/api/colunas/${agendar.id}/restaurar`)).status, 422)
  })

  test('ordenar por prazo (sem prazo por último), prioridade, título e cliente', async () => {
    const a = await ambiente()
    const fila = a.coluna('criacao', 'Fila')
    const d1 = await a.criarDemanda({ titulo: 'Bolo', prazo: '2026-10-20' })
    const d2 = await a.criarDemanda({ titulo: 'Abacaxi', prioridade: 'urgente', clienteId: a.clientes.icc.id })
    const d3 = await a.criarDemanda({ titulo: 'Caju', prazo: '2026-10-16', prazoHora: '09:00', prioridade: 'alta' })
    const d4 = await a.criarDemanda({ titulo: 'Damasco', prazo: '2026-10-16', clienteId: null })
    const eu = a.como(a.pessoas.design)
    let r = await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'prazo' })
    assert.deepEqual(r.corpo.ordem, [d3.id, d4.id, d1.id, d2.id])
    const boot = await eu.get('/api/bootstrap')
    const pos = (id: string) => boot.corpo.demandas.find((x: { id: string }) => x.id === id).posicao
    assert.ok(pos(d3.id) < pos(d4.id) && pos(d4.id) < pos(d1.id) && pos(d1.id) < pos(d2.id))
    r = await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'prioridade' })
    assert.deepEqual(r.corpo.ordem.slice(0, 2), [d2.id, d3.id])
    r = await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'titulo' })
    assert.deepEqual(r.corpo.ordem, [d2.id, d1.id, d3.id, d4.id])
    r = await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'cliente' })
    assert.equal(r.corpo.ordem.at(-1), d4.id)
    assert.equal(r.corpo.ordem.at(-2), d2.id)
    r = await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'criacao' })
    assert.deepEqual(r.corpo.ordem, [d1.id, d2.id, d3.id, d4.id])
    assert.equal((await eu.post(`/api/colunas/${fila.id}/ordenar`, { por: 'cor' })).status, 400)
  })

  test('mover todos os cards entre quadros passa pelo mover() (etiquetas §5.6) e não leva as concluídas antigas', async () => {
    const a = await ambiente()
    const [urgente, alteracao] = ['Urgente', 'Alteração'].map((n) => a.quadros.criacao.etiquetas.find((e) => e.nome === n)!.id)
    const pronto = a.coluna('criacao', 'Pronto')
    const d1 = await a.criarDemanda({ colunaId: pronto.id, etiquetaIds: [urgente!, alteracao!] })
    const d2 = await a.criarDemanda({ colunaId: pronto.id })
    const velha = await a.criarDemanda({ colunaId: pronto.id })
    rodar(a.db, "UPDATE demanda SET concluida_em = '2026-10-01T10:00:00.000Z' WHERE id = ?", velha.id)
    const destino = a.coluna('social', 'Agendar')
    const r = await a.como(a.pessoas.am).post(`/api/colunas/${pronto.id}/mover-cards`, { destinoColunaId: destino.id })
    assert.equal(r.status, 200)
    assert.deepEqual(r.corpo.movidas, [d1.id, d2.id])
    assert.deepEqual(r.corpo.proximas, [])
    const boot = (await a.como(a.pessoas.am).get('/api/bootstrap')).corpo
    const m1 = boot.demandas.find((x: { id: string }) => x.id === d1.id)
    assert.equal(m1.colunaId, destino.id)
    const alteracaoSocial = a.quadros.social.etiquetas.find((e) => e.nome === 'Alteração')!.id
    assert.deepEqual(m1.etiquetaIds, [alteracaoSocial])
    assert.equal(um<{ coluna_id: string }>(a.db, 'SELECT coluna_id FROM demanda WHERE id = ?', velha.id)!.coluna_id, pronto.id)
    const atv = JSON.parse(um<{ dados: string }>(a.db, "SELECT dados FROM atividade WHERE tipo = 'demanda.movida' AND demanda_id = ?", d1.id)!.dados)
    assert.equal(atv.via, 'coluna')
    assert.deepEqual(atv.etiquetasDeixadas, ['Urgente'])
    assert.equal((await a.como(a.pessoas.am).post(`/api/colunas/${destino.id}/mover-cards`, { destinoColunaId: destino.id })).status, 400)
  })

  test('arquivar todos os cards da coluna', async () => {
    const a = await ambiente()
    const fila = a.coluna('criacao', 'Fila')
    const d1 = await a.criarDemanda()
    const d2 = await a.criarDemanda()
    const r = await a.como(a.pessoas.design).post(`/api/colunas/${fila.id}/arquivar-cards`)
    assert.deepEqual(r.corpo.arquivadas, [d1.id, d2.id])
    assert.equal(um<{ n: number }>(a.db, 'SELECT count(*) AS n FROM demanda WHERE arquivado_em IS NOT NULL')!.n, 2)
  })
})
